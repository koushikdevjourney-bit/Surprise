function inr(amount) {
  return `₹${amount.toLocaleString('en-IN')}`
}

function experience(item) {
  const name = item.name
  const priceAmount = item.priceAmount
  return {
    title: name,
    startingPrice: item.startingPrice ?? inr(priceAmount),
    filters: item.filterKeys,
    ...item,
    name,
  }
}

