export function matchesExperienceFilter(item, filterId) {
  if (!filterId || filterId === 'all') return true
  if (filterId === 'under-1000') return (item.priceAmount ?? 0) < 1000
  if (filterId === 'premium') return (item.priceAmount ?? 0) >= 5000
  const keys = item.filterKeys ?? item.filters ?? []
  return keys.includes(filterId)
}

export function isDigitalExperience(item) {
  return item?.tier === 'digital' || DIGITAL_IDS.includes(item?.id)
}
